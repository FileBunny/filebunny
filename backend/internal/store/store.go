// Package store keeps ciphertext blobs on disk and their metadata in SQLite.
//
// Blobs are named by a random ID that the store generates; nothing the
// client sends ever ends up in a path.
package store

import (
	"context"
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"database/sql"
	"encoding/base64"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"time"

	_ "modernc.org/sqlite" // registers the "sqlite" driver
)

var (
	// ErrNotFound means the file does not exist or has expired.
	ErrNotFound = errors.New("store: not found")
	// ErrForbidden means the delete token does not match.
	ErrForbidden = errors.New("store: wrong delete token")
	// ErrInboxFull means an upload link has no uploads or bytes left.
	ErrInboxFull = errors.New("store: upload link full")
	// ErrTooManyInboxes means the server-wide cap on open links is reached.
	ErrTooManyInboxes = errors.New("store: too many upload links")
)

// File is the metadata of a stored blob.
type File struct {
	ID        string
	Size      int64
	CreatedAt time.Time
	ExpiresAt time.Time
	// MaxDownloads is the number of downloads allowed; 0 means unlimited.
	MaxDownloads int
	// Downloads counts the downloads started so far.
	Downloads int
	// Storage names the external service that holds the blob; empty means
	// this server's disk. RemoteRef is the server-generated name there.
	Storage   string
	RemoteRef string
}

// RemoteObject is a blob at an external service that must be deleted.
type RemoteObject struct {
	Storage string
	Ref     string
}

// DownloadsLeft returns how many downloads remain, or -1 if unlimited.
func (f File) DownloadsLeft() int {
	if f.MaxDownloads == 0 {
		return -1
	}
	return max(f.MaxDownloads-f.Downloads, 0)
}

// Store is safe for concurrent use.
type Store struct {
	db      *sql.DB
	blobDir string
	tmpDir  string
}

const (
	idBytes    = 16 // 128 bits
	tokenBytes = 32 // 256 bits
)

// idPattern matches IDs as generated by newRandom(idBytes).
var idPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{22}$`)

// migrations are applied in order; PRAGMA user_version records how many ran.
var migrations = []string{
	`CREATE TABLE files (
		id                TEXT PRIMARY KEY,
		delete_token_hash BLOB NOT NULL,
		size              INTEGER NOT NULL,
		created_at        INTEGER NOT NULL,
		expires_at        INTEGER NOT NULL
	) STRICT;
	CREATE INDEX files_expires_at ON files(expires_at);`,
	// max_downloads NULL means unlimited.
	`ALTER TABLE files ADD COLUMN max_downloads INTEGER;
	ALTER TABLE files ADD COLUMN downloads INTEGER NOT NULL DEFAULT 0;`,
	// Upload links. Files with an inbox_id belong to the link's owner and
	// are only served through the management token.
	`CREATE TABLE inboxes (
		id                TEXT PRIMARY KEY,
		manage_token_hash BLOB NOT NULL,
		public_key        BLOB NOT NULL,
		created_at        INTEGER NOT NULL,
		expires_at        INTEGER NOT NULL,
		max_uploads       INTEGER NOT NULL,
		uploads           INTEGER NOT NULL DEFAULT 0,
		max_bytes         INTEGER NOT NULL,
		bytes             INTEGER NOT NULL DEFAULT 0
	) STRICT;
	CREATE INDEX inboxes_expires_at ON inboxes(expires_at);
	ALTER TABLE files ADD COLUMN inbox_id TEXT;
	CREATE INDEX files_inbox_id ON files(inbox_id);`,
	// Blobs at an external service (storage NULL means this server's
	// disk). remote_trash holds blobs to delete there, not before
	// delete_after, so a download in progress can finish.
	`ALTER TABLE files ADD COLUMN storage TEXT;
	ALTER TABLE files ADD COLUMN remote_ref TEXT;
	CREATE TABLE remote_trash (
		storage      TEXT NOT NULL,
		remote_ref   TEXT NOT NULL,
		delete_after INTEGER NOT NULL,
		PRIMARY KEY (storage, remote_ref)
	) STRICT;`,
}

// Open opens (or creates) the store in dataDir.
func Open(dataDir string) (*Store, error) {
	s := &Store{
		blobDir: filepath.Join(dataDir, "blobs"),
		tmpDir:  filepath.Join(dataDir, "tmp"),
	}
	for _, d := range []string{dataDir, s.blobDir, s.tmpDir} {
		if err := os.MkdirAll(d, 0o700); err != nil {
			return nil, err
		}
	}

	dsn := "file:" + filepath.Join(dataDir, "filebunny.db") +
		"?_pragma=journal_mode(WAL)&_pragma=busy_timeout(5000)&_pragma=synchronous(NORMAL)"
	db, err := sql.Open("sqlite", dsn)
	if err != nil {
		return nil, err
	}
	// Queries are tiny; one connection avoids SQLITE_BUSY between writers.
	db.SetMaxOpenConns(1)
	s.db = db

	if err := s.migrate(); err != nil {
		db.Close()
		return nil, fmt.Errorf("store: migrate: %w", err)
	}
	return s, nil
}

func (s *Store) migrate() error {
	var version int
	if err := s.db.QueryRow(`PRAGMA user_version`).Scan(&version); err != nil {
		return err
	}
	for i := version; i < len(migrations); i++ {
		tx, err := s.db.Begin()
		if err != nil {
			return err
		}
		if _, err := tx.Exec(migrations[i]); err != nil {
			tx.Rollback()
			return fmt.Errorf("migration %d: %w", i+1, err)
		}
		if _, err := tx.Exec(fmt.Sprintf(`PRAGMA user_version = %d`, i+1)); err != nil {
			tx.Rollback()
			return err
		}
		if err := tx.Commit(); err != nil {
			return err
		}
	}
	return nil
}

// Close closes the database.
func (s *Store) Close() error {
	return s.db.Close()
}

// Put streams r to disk and records it. maxDownloads 0 means unlimited.
// It returns the metadata and the delete token; only a hash of the token
// is stored.
func (s *Store) Put(ctx context.Context, r io.Reader, now, expiresAt time.Time, maxDownloads int) (File, string, error) {
	p, err := s.Begin()
	if err != nil {
		return File{}, "", err
	}
	if _, err := p.Append(r); err != nil {
		p.Abort()
		return File{}, "", err
	}
	return s.Commit(ctx, p, now, expiresAt, maxDownloads)
}

// Pending is an upload that is written in parts and not yet visible. It is
// not safe for concurrent use.
type Pending struct {
	f    *os.File
	size int64
}

// Begin starts a pending upload in the temp directory. The caller must
// finish it with Commit or Abort.
func (s *Store) Begin() (*Pending, error) {
	f, err := os.CreateTemp(s.tmpDir, "upload-*")
	if err != nil {
		return nil, err
	}
	return &Pending{f: f}, nil
}

// Size returns the number of bytes appended so far.
func (p *Pending) Size() int64 { return p.size }

// Content returns the data appended so far, from the start, for sending
// it on to an external service. Do not Append while reading it.
func (p *Pending) Content() (io.ReadSeeker, error) {
	if _, err := p.f.Seek(0, io.SeekStart); err != nil {
		return nil, err
	}
	return io.NewSectionReader(p.f, 0, p.size), nil
}

// Append writes all of r. A part is all or nothing: if r fails, the data
// it wrote is discarded, so the same part can be sent again.
func (p *Pending) Append(r io.Reader) (int64, error) {
	n, err := io.Copy(p.f, r)
	if err != nil {
		if terr := p.f.Truncate(p.size); terr != nil {
			return 0, errors.Join(err, terr)
		}
		if _, serr := p.f.Seek(p.size, io.SeekStart); serr != nil {
			return 0, errors.Join(err, serr)
		}
		return 0, err
	}
	p.size += n
	return n, nil
}

// Abort discards the pending upload.
func (p *Pending) Abort() {
	p.f.Close()
	os.Remove(p.f.Name())
}

// Commit makes a pending upload a stored file; p must not be used after.
// maxDownloads 0 means unlimited. It returns the metadata and the delete
// token; only a hash of the token is stored.
func (s *Store) Commit(ctx context.Context, p *Pending, now, expiresAt time.Time, maxDownloads int) (File, string, error) {
	token := newRandom(tokenBytes)
	f, err := s.commit(ctx, p, now, expiresAt, maxDownloads, hashToken(token), "")
	if err != nil {
		return File{}, "", err
	}
	return f, token, nil
}

// CommitRemote records a file whose blob is at an external service under
// ref; the caller has uploaded it there. It returns the metadata and the
// delete token, like Commit.
func (s *Store) CommitRemote(ctx context.Context, size int64, storage, ref string, now, expiresAt time.Time, maxDownloads int) (File, string, error) {
	token := newRandom(tokenBytes)
	id := newRandom(idBytes)
	now, expiresAt = now.Truncate(time.Second), expiresAt.Truncate(time.Second)
	_, err := s.db.ExecContext(ctx,
		`INSERT INTO files (id, delete_token_hash, size, created_at, expires_at, max_downloads, storage, remote_ref) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
		id, hashToken(token), size, now.Unix(), expiresAt.Unix(), nullIfZero(maxDownloads), storage, ref)
	if err != nil {
		return File{}, "", err
	}
	f := File{ID: id, Size: size, CreatedAt: now, ExpiresAt: expiresAt, MaxDownloads: maxDownloads, Storage: storage, RemoteRef: ref}
	return f, token, nil
}

// CommitToInbox makes a pending upload a file of an upload link; p must
// not be used after. The link's upload and byte counters are updated in
// the same transaction, so parallel uploads can never exceed its limits:
// ErrInboxFull when they would, ErrNotFound when the link is gone or
// expired. Nobody gets a delete token; the link's owner deletes.
func (s *Store) CommitToInbox(ctx context.Context, p *Pending, inboxID string, now, expiresAt time.Time) (File, error) {
	if !idPattern.MatchString(inboxID) {
		p.Abort()
		return File{}, ErrNotFound
	}
	return s.commit(ctx, p, now, expiresAt, 0, hashToken(newRandom(tokenBytes)), inboxID)
}

func (s *Store) commit(ctx context.Context, p *Pending, now, expiresAt time.Time, maxDownloads int, tokenHash []byte, inboxID string) (File, error) {
	tmpName := p.f.Name()
	defer os.Remove(tmpName) // no-op once renamed

	err := p.f.Sync()
	if cerr := p.f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return File{}, err
	}

	id := newRandom(idBytes)
	// The database stores whole seconds; return what Get will return.
	now, expiresAt = now.Truncate(time.Second), expiresAt.Truncate(time.Second)
	f := File{ID: id, Size: p.size, CreatedAt: now, ExpiresAt: expiresAt, MaxDownloads: maxDownloads}

	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return File{}, err
	}
	defer tx.Rollback() // no-op after Commit
	if inboxID != "" {
		res, err := tx.ExecContext(ctx,
			`UPDATE inboxes SET uploads = uploads + 1, bytes = bytes + ?
			WHERE id = ? AND expires_at > ? AND uploads < max_uploads AND bytes + ? <= max_bytes`,
			p.size, inboxID, now.Unix(), p.size)
		if err != nil {
			return File{}, err
		}
		if n, err := res.RowsAffected(); err != nil {
			return File{}, err
		} else if n == 0 {
			if _, err := s.openInbox(ctx, tx, inboxID, now); err != nil {
				return File{}, err
			}
			return File{}, ErrInboxFull
		}
	}
	// Insert the row before the rename: the primary key guarantees the ID
	// is unused, so the rename can never overwrite another file's blob.
	// Until the rename, Get reports the file as not found.
	_, err = tx.ExecContext(ctx,
		`INSERT INTO files (id, delete_token_hash, size, created_at, expires_at, max_downloads, inbox_id) VALUES (?, ?, ?, ?, ?, ?, ?)`,
		id, tokenHash, p.size, now.Unix(), expiresAt.Unix(), nullIfZero(maxDownloads), nullIfEmpty(inboxID))
	if err != nil {
		return File{}, err
	}
	if err := tx.Commit(); err != nil {
		return File{}, err
	}
	if err := os.Rename(tmpName, s.blobPath(id)); err != nil {
		// Leaves the link's counters as they are: that upload is used up.
		s.db.ExecContext(context.WithoutCancel(ctx), `DELETE FROM files WHERE id = ?`, id)
		return File{}, err
	}
	return f, nil
}

// available is the SQL condition for a file that can still be downloaded.
// Files of an upload link are never available this way.
const available = `expires_at > ? AND (max_downloads IS NULL OR downloads < max_downloads) AND inbox_id IS NULL`

const fileColumns = `size, created_at, expires_at, downloads, max_downloads, storage, remote_ref`

// immediately is a deleteAfter for blobs that may go at once.
var immediately = time.Unix(0, 0)

// downloadGrace is how long a remote blob is kept after its last allowed
// download started, so that download can finish.
const downloadGrace = time.Hour

// Get counts a download and returns the metadata and an open handle to the
// blob. The caller must close the handle. For a blob at an external service
// the handle is nil and the caller fetches f.RemoteRef. Expired files and
// files without downloads left are reported as ErrNotFound. The counter is
// updated in one statement, so concurrent downloads can never exceed the
// limit; the last allowed download removes the file (the open handle keeps
// working, a remote blob stays for downloadGrace).
func (s *Store) Get(ctx context.Context, id string, now time.Time) (File, *os.File, error) {
	if !idPattern.MatchString(id) {
		return File{}, nil, ErrNotFound
	}
	f, err := scanFile(id, s.db.QueryRowContext(ctx,
		`UPDATE files SET downloads = downloads + 1 WHERE id = ? AND `+available+` RETURNING `+fileColumns,
		id, now.Unix()))
	if err != nil {
		return File{}, nil, err
	}
	if f.Storage != "" {
		if f.DownloadsLeft() == 0 {
			_ = s.remove(context.WithoutCancel(ctx), id, now.Add(downloadGrace))
		}
		return f, nil, nil
	}

	blob, err := os.Open(s.blobPath(id))
	if errors.Is(err, os.ErrNotExist) {
		return File{}, nil, ErrNotFound
	}
	if err != nil {
		return File{}, nil, err
	}
	if f.DownloadsLeft() == 0 {
		// If this fails, the row stays unavailable (no downloads left) and
		// cleanup removes it when it expires.
		_ = s.remove(context.WithoutCancel(ctx), id, now)
	}
	return f, blob, nil
}

// Stat returns the metadata without counting a download.
func (s *Store) Stat(ctx context.Context, id string, now time.Time) (File, error) {
	if !idPattern.MatchString(id) {
		return File{}, ErrNotFound
	}
	return scanFile(id, s.db.QueryRowContext(ctx,
		`SELECT `+fileColumns+` FROM files WHERE id = ? AND `+available,
		id, now.Unix()))
}

func scanFile(id string, row *sql.Row) (File, error) {
	f := File{ID: id}
	var created, expires int64
	var maxDownloads sql.NullInt64
	var storage, ref sql.NullString
	err := row.Scan(&f.Size, &created, &expires, &f.Downloads, &maxDownloads, &storage, &ref)
	if errors.Is(err, sql.ErrNoRows) {
		return File{}, ErrNotFound
	}
	if err != nil {
		return File{}, err
	}
	f.CreatedAt, f.ExpiresAt = time.Unix(created, 0), time.Unix(expires, 0)
	f.MaxDownloads = int(maxDownloads.Int64)
	f.Storage, f.RemoteRef = storage.String, ref.String
	return f, nil
}

// Delete removes a file if token matches its delete token. Expired files
// are reported as ErrNotFound, like in Get; cleanup removes them.
func (s *Store) Delete(ctx context.Context, id, token string, now time.Time) error {
	if !idPattern.MatchString(id) {
		return ErrNotFound
	}
	var stored []byte
	err := s.db.QueryRowContext(ctx,
		`SELECT delete_token_hash FROM files WHERE id = ? AND expires_at > ? AND inbox_id IS NULL`,
		id, now.Unix()).Scan(&stored)
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	if err != nil {
		return err
	}
	if subtle.ConstantTimeCompare(stored, hashToken(token)) != 1 {
		return ErrForbidden
	}
	return s.remove(ctx, id, now)
}

// TotalSize returns the combined size of all files on this server's disk,
// including expired ones that cleanup has not removed yet (they still use
// disk). Blobs at an external service do not count.
func (s *Store) TotalSize(ctx context.Context) (int64, error) {
	var total int64
	err := s.db.QueryRowContext(ctx, `SELECT COALESCE(SUM(size), 0) FROM files WHERE storage IS NULL`).Scan(&total)
	return total, err
}

// DeleteExpired removes every file that expired at or before now and
// returns how many were removed.
func (s *Store) DeleteExpired(ctx context.Context, now time.Time) (int, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT id FROM files WHERE expires_at <= ?`, now.Unix())
	if err != nil {
		return 0, err
	}
	var ids []string
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return 0, err
		}
		ids = append(ids, id)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return 0, err
	}

	n := 0
	for _, id := range ids {
		if err := s.remove(ctx, id, now); err != nil {
			return n, err
		}
		n++
	}
	// An expired upload link stays while it holds files, so its owner can
	// still fetch them; then it goes too.
	_, err = s.db.ExecContext(ctx,
		`DELETE FROM inboxes WHERE expires_at <= ? AND NOT EXISTS (SELECT 1 FROM files WHERE inbox_id = inboxes.id)`,
		now.Unix())
	return n, err
}

// RemoveOrphans deletes leftover temp files and blobs without a database
// row (for example after a crash). Call it only at startup, before serving
// requests: a concurrent Put has a blob on disk before its row exists.
func (s *Store) RemoveOrphans(ctx context.Context) (int, error) {
	n := 0
	tmps, err := os.ReadDir(s.tmpDir)
	if err != nil {
		return 0, err
	}
	for _, e := range tmps {
		if err := os.Remove(filepath.Join(s.tmpDir, e.Name())); err != nil {
			return n, err
		}
		n++
	}

	blobs, err := os.ReadDir(s.blobDir)
	if err != nil {
		return n, err
	}
	for _, e := range blobs {
		var one int
		err := s.db.QueryRowContext(ctx, `SELECT 1 FROM files WHERE id = ?`, e.Name()).Scan(&one)
		if err == nil {
			continue
		}
		if !errors.Is(err, sql.ErrNoRows) {
			return n, err
		}
		if err := os.Remove(filepath.Join(s.blobDir, e.Name())); err != nil {
			return n, err
		}
		n++
	}
	return n, nil
}

// RemoteDue returns remote blobs whose deletion is due at now.
func (s *Store) RemoteDue(ctx context.Context, now time.Time) ([]RemoteObject, error) {
	rows, err := s.db.QueryContext(ctx,
		`SELECT storage, remote_ref FROM remote_trash WHERE delete_after <= ?`, now.Unix())
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []RemoteObject
	for rows.Next() {
		var o RemoteObject
		if err := rows.Scan(&o.Storage, &o.Ref); err != nil {
			return nil, err
		}
		out = append(out, o)
	}
	return out, rows.Err()
}

// RemoteDeleted records that a remote blob is gone.
func (s *Store) RemoteDeleted(ctx context.Context, o RemoteObject) error {
	_, err := s.db.ExecContext(ctx, `DELETE FROM remote_trash WHERE storage = ? AND remote_ref = ?`, o.Storage, o.Ref)
	return err
}

// remove deletes the row first, so the file is unreachable even if removing
// the blob fails; RemoveOrphans picks up such leftovers. A remote blob goes
// to remote_trash in the same transaction, to be deleted from deleteAfter.
func (s *Store) remove(ctx context.Context, id string, deleteAfter time.Time) error {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback() // no-op after Commit
	var storage, ref sql.NullString
	err = tx.QueryRowContext(ctx, `DELETE FROM files WHERE id = ? RETURNING storage, remote_ref`, id).Scan(&storage, &ref)
	if errors.Is(err, sql.ErrNoRows) {
		return nil
	}
	if err != nil {
		return err
	}
	if storage.Valid {
		if _, err := tx.ExecContext(ctx,
			`INSERT OR IGNORE INTO remote_trash (storage, remote_ref, delete_after) VALUES (?, ?, ?)`,
			storage.String, ref.String, deleteAfter.Unix()); err != nil {
			return err
		}
	}
	if err := tx.Commit(); err != nil {
		return err
	}
	if storage.Valid {
		return nil
	}
	if err := os.Remove(s.blobPath(id)); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

func (s *Store) blobPath(id string) string {
	return filepath.Join(s.blobDir, id)
}

func newRandom(n int) string {
	b := make([]byte, n)
	rand.Read(b) // never returns an error since Go 1.24
	return base64.RawURLEncoding.EncodeToString(b)
}

func nullIfEmpty(s string) any {
	if s == "" {
		return nil
	}
	return s
}

func nullIfZero(n int) any {
	if n == 0 {
		return nil
	}
	return n
}

func hashToken(token string) []byte {
	h := sha256.Sum256([]byte(token))
	return h[:]
}
