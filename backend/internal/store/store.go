// Package store keeps ciphertext blobs on disk and their metadata in SQLite.
//
// Blobs are named by a random ID that the store generates; nothing the
// client sends ever ends up in a path.
package store

import (
	"context"
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"database/sql"
	"encoding/base64"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"time"

	_ "modernc.org/sqlite" // registers the "sqlite" driver
)

var (
	// ErrNotFound means the file does not exist or has expired.
	ErrNotFound = errors.New("store: not found")
	// ErrForbidden means the delete token does not match.
	ErrForbidden = errors.New("store: wrong delete token")
)

// File is the metadata of a stored blob.
type File struct {
	ID        string
	Size      int64
	CreatedAt time.Time
	ExpiresAt time.Time
}

// Store is safe for concurrent use.
type Store struct {
	db      *sql.DB
	blobDir string
	tmpDir  string
}

const (
	idBytes    = 16 // 128 bits
	tokenBytes = 32 // 256 bits
)

// idPattern matches IDs as generated by newRandom(idBytes).
var idPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{22}$`)

// migrations are applied in order; PRAGMA user_version records how many ran.
var migrations = []string{
	`CREATE TABLE files (
		id                TEXT PRIMARY KEY,
		delete_token_hash BLOB NOT NULL,
		size              INTEGER NOT NULL,
		created_at        INTEGER NOT NULL,
		expires_at        INTEGER NOT NULL
	) STRICT;
	CREATE INDEX files_expires_at ON files(expires_at);`,
}

// Open opens (or creates) the store in dataDir.
func Open(dataDir string) (*Store, error) {
	s := &Store{
		blobDir: filepath.Join(dataDir, "blobs"),
		tmpDir:  filepath.Join(dataDir, "tmp"),
	}
	for _, d := range []string{dataDir, s.blobDir, s.tmpDir} {
		if err := os.MkdirAll(d, 0o700); err != nil {
			return nil, err
		}
	}

	dsn := "file:" + filepath.Join(dataDir, "filebunny.db") +
		"?_pragma=journal_mode(WAL)&_pragma=busy_timeout(5000)&_pragma=synchronous(NORMAL)"
	db, err := sql.Open("sqlite", dsn)
	if err != nil {
		return nil, err
	}
	// Queries are tiny; one connection avoids SQLITE_BUSY between writers.
	db.SetMaxOpenConns(1)
	s.db = db

	if err := s.migrate(); err != nil {
		db.Close()
		return nil, fmt.Errorf("store: migrate: %w", err)
	}
	return s, nil
}

func (s *Store) migrate() error {
	var version int
	if err := s.db.QueryRow(`PRAGMA user_version`).Scan(&version); err != nil {
		return err
	}
	for i := version; i < len(migrations); i++ {
		tx, err := s.db.Begin()
		if err != nil {
			return err
		}
		if _, err := tx.Exec(migrations[i]); err != nil {
			tx.Rollback()
			return fmt.Errorf("migration %d: %w", i+1, err)
		}
		if _, err := tx.Exec(fmt.Sprintf(`PRAGMA user_version = %d`, i+1)); err != nil {
			tx.Rollback()
			return err
		}
		if err := tx.Commit(); err != nil {
			return err
		}
	}
	return nil
}

// Close closes the database.
func (s *Store) Close() error {
	return s.db.Close()
}

// Put streams r to disk and records it. It returns the metadata and the
// delete token; only a hash of the token is stored.
func (s *Store) Put(ctx context.Context, r io.Reader, now, expiresAt time.Time) (File, string, error) {
	tmp, err := os.CreateTemp(s.tmpDir, "upload-*")
	if err != nil {
		return File{}, "", err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName) // no-op once renamed

	size, err := io.Copy(tmp, r)
	if err == nil {
		err = tmp.Sync()
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return File{}, "", err
	}

	id := newRandom(idBytes)
	token := newRandom(tokenBytes)
	// The database stores whole seconds; return what Get will return.
	now, expiresAt = now.Truncate(time.Second), expiresAt.Truncate(time.Second)
	f := File{ID: id, Size: size, CreatedAt: now, ExpiresAt: expiresAt}

	// Insert the row before the rename: the primary key guarantees the ID
	// is unused, so the rename can never overwrite another file's blob.
	// Until the rename, Get reports the file as not found.
	_, err = s.db.ExecContext(ctx,
		`INSERT INTO files (id, delete_token_hash, size, created_at, expires_at) VALUES (?, ?, ?, ?, ?)`,
		id, hashToken(token), size, now.Unix(), expiresAt.Unix())
	if err != nil {
		return File{}, "", err
	}
	if err := os.Rename(tmpName, s.blobPath(id)); err != nil {
		s.db.ExecContext(context.WithoutCancel(ctx), `DELETE FROM files WHERE id = ?`, id)
		return File{}, "", err
	}
	return f, token, nil
}

// Get returns the metadata and an open handle to the blob. The caller must
// close the handle. Expired files are reported as ErrNotFound.
func (s *Store) Get(ctx context.Context, id string, now time.Time) (File, *os.File, error) {
	if !idPattern.MatchString(id) {
		return File{}, nil, ErrNotFound
	}
	f := File{ID: id}
	var created, expires int64
	err := s.db.QueryRowContext(ctx,
		`SELECT size, created_at, expires_at FROM files WHERE id = ? AND expires_at > ?`,
		id, now.Unix()).Scan(&f.Size, &created, &expires)
	if errors.Is(err, sql.ErrNoRows) {
		return File{}, nil, ErrNotFound
	}
	if err != nil {
		return File{}, nil, err
	}
	f.CreatedAt, f.ExpiresAt = time.Unix(created, 0), time.Unix(expires, 0)

	blob, err := os.Open(s.blobPath(id))
	if errors.Is(err, os.ErrNotExist) {
		return File{}, nil, ErrNotFound
	}
	if err != nil {
		return File{}, nil, err
	}
	return f, blob, nil
}

// Delete removes a file if token matches its delete token. Expired files
// are reported as ErrNotFound, like in Get; cleanup removes them.
func (s *Store) Delete(ctx context.Context, id, token string, now time.Time) error {
	if !idPattern.MatchString(id) {
		return ErrNotFound
	}
	var stored []byte
	err := s.db.QueryRowContext(ctx,
		`SELECT delete_token_hash FROM files WHERE id = ? AND expires_at > ?`,
		id, now.Unix()).Scan(&stored)
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	if err != nil {
		return err
	}
	if subtle.ConstantTimeCompare(stored, hashToken(token)) != 1 {
		return ErrForbidden
	}
	return s.remove(ctx, id)
}

// TotalSize returns the combined size of all stored files, including
// expired ones that cleanup has not removed yet (they still use disk).
func (s *Store) TotalSize(ctx context.Context) (int64, error) {
	var total int64
	err := s.db.QueryRowContext(ctx, `SELECT COALESCE(SUM(size), 0) FROM files`).Scan(&total)
	return total, err
}

// DeleteExpired removes every file that expired at or before now and
// returns how many were removed.
func (s *Store) DeleteExpired(ctx context.Context, now time.Time) (int, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT id FROM files WHERE expires_at <= ?`, now.Unix())
	if err != nil {
		return 0, err
	}
	var ids []string
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return 0, err
		}
		ids = append(ids, id)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return 0, err
	}

	n := 0
	for _, id := range ids {
		if err := s.remove(ctx, id); err != nil {
			return n, err
		}
		n++
	}
	return n, nil
}

// RemoveOrphans deletes leftover temp files and blobs without a database
// row (for example after a crash). Call it only at startup, before serving
// requests: a concurrent Put has a blob on disk before its row exists.
func (s *Store) RemoveOrphans(ctx context.Context) (int, error) {
	n := 0
	tmps, err := os.ReadDir(s.tmpDir)
	if err != nil {
		return 0, err
	}
	for _, e := range tmps {
		if err := os.Remove(filepath.Join(s.tmpDir, e.Name())); err != nil {
			return n, err
		}
		n++
	}

	blobs, err := os.ReadDir(s.blobDir)
	if err != nil {
		return n, err
	}
	for _, e := range blobs {
		var one int
		err := s.db.QueryRowContext(ctx, `SELECT 1 FROM files WHERE id = ?`, e.Name()).Scan(&one)
		if err == nil {
			continue
		}
		if !errors.Is(err, sql.ErrNoRows) {
			return n, err
		}
		if err := os.Remove(filepath.Join(s.blobDir, e.Name())); err != nil {
			return n, err
		}
		n++
	}
	return n, nil
}

// remove deletes the row first, so the file is unreachable even if removing
// the blob fails; RemoveOrphans picks up such leftovers.
func (s *Store) remove(ctx context.Context, id string) error {
	if _, err := s.db.ExecContext(ctx, `DELETE FROM files WHERE id = ?`, id); err != nil {
		return err
	}
	if err := os.Remove(s.blobPath(id)); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

func (s *Store) blobPath(id string) string {
	return filepath.Join(s.blobDir, id)
}

func newRandom(n int) string {
	b := make([]byte, n)
	rand.Read(b) // never returns an error since Go 1.24
	return base64.RawURLEncoding.EncodeToString(b)
}

func hashToken(token string) []byte {
	h := sha256.Sum256([]byte(token))
	return h[:]
}
